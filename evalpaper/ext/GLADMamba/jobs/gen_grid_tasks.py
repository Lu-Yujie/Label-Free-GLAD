"""Write jobs/tasks_grid.txt: the GLADMamba E5 grid (UB9 + MUTAG) x 5 folds x {ubgold, hpfree}, longest first.

Runtime per task = startup + s/epoch(train) x num_epoch + s/eval x n_eval, from the CPU timing runs of the debug
job <jobid> (smoke parts, tag tcpu, fold 0, 10 epochs, 4 threads). Threads per task: 4, or 2 for tasks estimated
< 15 min (2 threads measured as fast as 4 on COX2/PROTEINS_full; 8 threads gave only -18% s/epoch on REDDIT-B).
Memory estimate = 1.5 x measured peak RSS + 1 GB. Finished runs are skipped by the pool anyway.
Appended at the end: 10 reproduction-diagnostic runs (BZR, COX2 ubgold; tag orig; --diag_orig: 100% training
normals, seeds trial+1), never part of the grid (collect.py ignores tagged runs).
    python3 -B jobs/gen_grid_tasks.py
"""
import os  # release: GLAD_DATA_ROOT / GLAD_ENVS
import glob
import json
import os.path as osp

HERE = osp.dirname(osp.abspath(__file__))
SMOKE = (os.environ.get("GLAD_DATA_ROOT", "glad_data") + "/ext_gladmamba/smoke/parts")
DS10 = ["AIDS", "BZR", "COX2", "DHFR", "ENZYMES", "NCI1", "PROTEINS_full", "IMDB-BINARY", "REDDIT-BINARY", "MUTAG"]


def timing(ds, hp, tag="tcpu"):
    fn = osp.join(SMOKE, f"GLADMamba_{ds}_fold0" + ("_hpfree" if hp == "hpfree" else "") + f"_{tag}.json")
    if not osp.exists(fn):
        return None
    m = json.load(open(fn))["meta"]
    startup = m["seconds"] - m["seconds_train_this_segment"] - m["seconds_eval_this_segment"]
    return dict(spe=m["sec_per_epoch_train"], spv=m["seconds_eval_this_segment"] / max(1, m["n_eval"]),
                startup=startup, rss=m["memory"]["maxrss_gb"])


def main():
    import sys
    sys.path.insert(0, osp.dirname(HERE))
    import run_method as R
    rows = []
    for ds in DS10:
        for hp in ("ubgold", "hpfree"):
            a, _, _ = R.resolve_hparams(ds, hp)
            t = timing(ds, hp)
            if t is None:
                raise SystemExit(f"no timing run for {ds} {hp}")
            n_eval = a.num_epoch // a.eval_freq + (1 if a.num_epoch % a.eval_freq else 0)
            est = t["startup"] + t["spe"] * a.num_epoch + t["spv"] * n_eval
            th = 2 if est < 15 * 60 else 4
            mem = round(1.5 * t["rss"] + 1, 1)
            for f in range(5):
                rows.append((est, ds, f, hp, mem, th))
    rows.sort(key=lambda r: (-r[0], r[1], r[3], r[2]))
    out = osp.join(HERE, "tasks_grid.txt")
    with open(out, "w") as fh:
        fh.write("# GLADMamba E5 grid, longest first (est. seconds at 4 threads from debug-job CPU timing); "
                 "generated by jobs/gen_grid_tasks.py; read at job start\n")
        for est, ds, f, hp, mem, th in rows:
            fh.write(f"GLADMamba {ds} {f} {hp} cpu mem={mem} threads={th}   # est {est/60:.1f} min\n")
        fh.write("# reproduction diagnostics (tagged, not grid runs)\n")
        for ds, th in (("COX2", 2), ("BZR", 2)):
            for f in range(5):
                fh.write(f"GLADMamba {ds} {f} ubgold cpu mem=3 threads={th} tag=orig diag_orig\n")
    tot = sum(r[0] * r[5] for r in rows) / 3600
    print(f"{len(rows)} tasks -> {out}; longest {rows[0][0]/3600:.2f} h ({rows[0][1]} {rows[0][3]}); "
          f"sum est core-hours (threads x est) {tot:.1f}")


if __name__ == "__main__":
    main()
